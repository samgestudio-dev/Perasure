#!/usr/bin/env python3
"""rem-tokens.py — the rem version of the design tokens, for pages that size everything in rem (prototypes/app and shared/ps-ui).

Reads tokens/tokens.css (never writes it: that folder belongs to the token pipeline, tools/sync-tokens.py) and writes
tokens-rem/tokens-rem.css: the same custom properties for every length primitive, in rem (1rem = 16 px at the default text size):

  --font-size-N, --font-line-height-N   → calc(N/16 rem * var(--ps-tx, 1))   text: also follows the extra text scale (see below)
  --spacing-N, --radius-N               → N/16 rem                            spacing and corners
  --radius-999 (the pill)               → kept in px (it only has to be large)
  --stroke-width-*, --blur-*, shadows   → kept in px (hairlines stay crisp; effects are not layout)

Every semantic token (--spacing-gap-md, --font-size-body-md, …) points at these primitives with var(), so loading this file after
tokens/tokens.css turns the whole system into rem without copying a single semantic token.

--ps-tx is set by shared/ps-ui/phone-fit.js: the part of the phone's text size the layout does not follow (above 130 %, only text grows).

Usage: python3 tools/rem-tokens.py            write tokens-rem/tokens-rem.css (tools/stamp.py runs it before every commit)
       python3 tools/rem-tokens.py --check    exit 1 if the file is out of date
Prints one line; never prints the tokens.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tokens', 'tokens.css')
OUT = os.path.join(ROOT, 'tokens-rem', 'tokens-rem.css')
TEXT = ('font-size', 'font-line-height')
BOX = ('spacing', 'radius')


def rem(px):
    v = float(px) / 16
    s = ('%.4f' % v).rstrip('0').rstrip('.')
    return '0' if s in ('0', '-0') else s + 'rem'


def build():
    src = open(SRC, encoding='utf-8').read()
    ver = re.search(r'tokens v?(\d+\.\d+\.\d+)', src) or re.search(r'"?version"?\s*[:=]\s*"?(\d+\.\d+\.\d+)', src)
    lines, n = [], {'text': 0, 'box': 0}
    for name, group, px in re.findall(r'^\s*(--([a-z]+(?:-[a-z]+)*)-[0-9a-z.]+):\s*(-?[0-9.]+)px\s*;', src, re.M):
        if group in TEXT:
            lines.append('  %s: calc(%s * var(--ps-tx, 1));' % (name, rem(px))); n['text'] += 1
        elif group in BOX and float(px) < 999:
            lines.append('  %s: %s;' % (name, rem(px))); n['box'] += 1
    head = ('/* GENERATED by tools/rem-tokens.py from tokens/tokens.css%s — do not edit; run the script (tools/stamp.py does).\n'
            '   The length primitives in rem (1rem = 16 px at the default text size). Load it right after tokens/tokens.css. */\n') % (
            ' v' + ver.group(1) if ver else '')
    return head + ':root {\n' + '\n'.join(lines) + '\n}\n', n


def main():
    css, n = build()
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if '--check' in sys.argv:
        if old != css:
            print('tokens-rem/tokens-rem.css is out of date: run python3 tools/rem-tokens.py'); sys.exit(1)
        print('tokens-rem/tokens-rem.css is up to date'); return
    if old != css:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        open(OUT, 'w', encoding='utf-8').write(css)
    print('tokens-rem/tokens-rem.css: %d text and %d spacing / radius tokens in rem%s' % (n['text'], n['box'], '' if old != css else ' (unchanged)'))


if __name__ == '__main__':
    main()
