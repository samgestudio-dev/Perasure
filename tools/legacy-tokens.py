"""Keep an older token version usable: write tokens/legacy/<version>.css from that version's tokens.css.

    python3 tools/legacy-tokens.py <git-ref> [<version>]     e.g.  tokens-v2026.11.12  (or a commit)

The file holds only what the current tokens.css no longer has as it was: every CSS name the newer version removed,
renamed or gave a new value, declared with its old value (and the .ps-text-* classes that changed). So:

  - code that still uses an old name (--gradient-bottom-nav-filled, --font-family-satoshi) keeps working if it loads
    the legacy file after tokens.css;
  - loading it after tokens.css brings back the whole older look (names that changed value get their old value).

Owner's rule (2026-11-17): a token update keeps the old CSS names and values. Run this after tools/sync-tokens.py,
with the previous version's tag. Generated — do not edit the output by hand.
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECL = re.compile(r'^\s*(--[\w-]+):\s*(.*?);(\s*/\*.*\*/)?\s*$')
CLASS = re.compile(r'^(\.ps-text-[\w-]+)\s*\{(.*)\}\s*$')


def parse(css):
    decl, cls = {}, {}
    for line in css.splitlines():
        m = DECL.match(line)
        if m:
            decl[m.group(1)] = m.group(2)
            continue
        m = CLASS.match(line.strip())
        if m:
            cls[m.group(1)] = m.group(2).strip()
    return decl, cls


def main(argv):
    if not argv:
        print(__doc__)
        return 1
    ref = argv[0]
    old_css = subprocess.check_output(['git', 'show', '%s:tokens/tokens.css' % ref], cwd=ROOT).decode('utf-8')
    version = argv[1] if len(argv) > 1 else re.search(r'tokens v([\d.]+)', old_css).group(1)
    new_css = open(os.path.join(ROOT, 'tokens', 'tokens.css'), encoding='utf-8').read()
    new_version = re.search(r'tokens v([\d.]+)', new_css).group(1)
    od, oc = parse(old_css)
    nd, nc = parse(new_css)
    removed = [k for k in od if k not in nd]
    changed = [k for k in od if k in nd and nd[k] != od[k]]
    # an old value may refer to a name that only the old version had: pull those in too
    need, seen = list(removed + changed), set()
    while need:
        k = need.pop()
        if k in seen:
            continue
        seen.add(k)
        for ref_name in re.findall(r'var\((--[\w-]+)\)', od[k]):
            if ref_name in od and (ref_name not in nd or nd[ref_name] != od[ref_name]):
                need.append(ref_name)
    cls = [k for k in oc if k not in nc or nc[k] != oc[k]]
    out = ['/* PeraSure design tokens — legacy v%s, kept after the update to v%s (owner: old CSS names and values stay usable).' % (version, new_version),
           '   Generated by tools/legacy-tokens.py from git %s:tokens/tokens.css — do not edit by hand.' % ref,
           '   Load it AFTER tokens/tokens.css: old names keep working, and names that changed value get their old value back',
           '   (the whole page then looks as it did in v%s). What changed and why: tokens/CHANGELOG.md → %s. */' % (version, new_version),
           '', ':root {', '  /* removed or renamed in v%s */' % new_version]
    out += ['  %s: %s;' % (k, od[k]) for k in od if k in seen and k not in nd]
    out += ['', '  /* same name, new value in v%s — the old value */' % new_version]
    out += ['  %s: %s;' % (k, od[k]) for k in od if k in seen and k in nd]
    out += ['}']
    if cls:
        out += ['', '/* text styles that changed in v%s */' % new_version] + ['%s { %s }' % (k, oc[k]) for k in cls]
    path = os.path.join(ROOT, 'tokens', 'legacy', '%s.css' % version)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('tokens/legacy/%s.css: %d removed / renamed, %d with their old value, %d text classes' % (
        version, len([k for k in seen if k not in nd]), len([k for k in seen if k in nd]), len(cls)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
