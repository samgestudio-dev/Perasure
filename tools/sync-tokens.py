"""Update the design tokens from a Figma export, with a version and a changelog entry.

    python3 tools/sync-tokens.py <export.json>   apply a full export (Figma plugin) or a patch (agent route;
                   [<part1.json> …]              pass every part of a multi-part patch), then bump the version,
                                                 prepend tokens/CHANGELOG.md and rebuild
    python3 tools/sync-tokens.py --digest        print the repo snapshot's digest (one line, for the agent route)
    python3 tools/sync-tokens.py --check         fail if a generated file is stale (CI)

    --message-out FILE   also write a commit message (first line = summary)

Only short lines go to stdout, so an agent running this reads a summary, never the token data.
"""
import copy, datetime, json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tokenlib import bucket, digest, sort_snapshot  # noqa: E402
import importlib.util  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOK = os.path.join(ROOT, 'tokens')
P = {k: os.path.join(TOK, f) for k, f in {
    'snap': 'figma-export.json', 'version': 'version.json', 'digest': 'digest.json', 'log': 'CHANGELOG.md',
    'css': 'tokens.css', 'json': 'tokens.json'}.items()}
PLUGIN = os.path.join(ROOT, 'tools', 'figma-tokens')
TZ = datetime.timezone(datetime.timedelta(hours=8))
DEFAULT_URL = 'https://www.figma.com/design/OBsvf42AiRapcRrasD7KNm/PeraSure-design-system'
LOG_HEAD = ('# Token changelog\n\nNewest first. Each version is the git tag `tokens-v<version>`; '
            'generated by `tools/sync-tokens.py`.\n\n')

spec = importlib.util.spec_from_file_location('build_tokens', os.path.join(ROOT, 'tools', 'build-tokens.py'))
bt = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bt)


def rd(p, default=None):
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else default


def wr(p, text):
    open(p, 'w', encoding='utf-8').write(text)


def plugin_code():
    core = open(os.path.join(PLUGIN, 'core.js'), encoding='utf-8').read()
    glue = open(os.path.join(PLUGIN, 'plugin', 'glue.js'), encoding='utf-8').read()
    return '// Generated by tools/sync-tokens.py from ../core.js + glue.js — do not edit by hand.\n' + core + '\n' + glue


def labels(snap):
    out = {'collections': 'Collections', 's:text': 'Text styles', 's:effect': 'Effect styles', 's:paint': 'Paint styles'}
    for c in snap['collections']:
        out['v:' + c['id']] = c['name'] + ' variables'
    return out


def digest_file(snap, version):
    return json.dumps({'version': version['version'], 'labels': labels(snap), 'digest': digest(snap)},
                      ensure_ascii=False, indent=1) + '\n'


def outputs(snap, version):
    css, js, info = bt.build(snap, version)
    return {P['css']: css, P['json']: js, P['digest']: digest_file(snap, version),
            os.path.join(PLUGIN, 'plugin', 'code.js'): plugin_code()}, info


# ---- applying an export ------------------------------------------------------------------------
def merge(items, gp):
    idx, repl = set(gp['buckets']), {it['id']: it for it in gp['items']}
    out = []
    for it in items:
        if bucket(it['id']) in idx:
            if it['id'] in repl:
                out.append(repl.pop(it['id']))
        else:
            out.append(it)
    return out + [it for it in gp['items'] if it['id'] in repl]


def apply_patch(old, patch):
    new = copy.deepcopy(old)
    g = patch['groups']
    if 'collections' in g:
        cols = merge([{k: v for k, v in c.items() if k != 'variables'} for c in new['collections']], g['collections'])
        vars_by = {c['id']: c['variables'] for c in new['collections']}
        new['collections'] = [dict(c, variables=vars_by.get(c['id'], [])) for c in cols]
    for c in new['collections']:
        if 'v:' + c['id'] in g:
            c['variables'] = merge(c['variables'], g['v:' + c['id']])
    for k in ('text', 'effect', 'paint'):
        if 's:' + k in g:
            new['styles'][k] = merge(new['styles'][k], g['s:' + k])
    return new


# ---- describing a change -----------------------------------------------------------------------
def show(v, rec_type=None, name=''):
    if isinstance(v, dict) and 'alias' in v:
        return '→ `%s`' % v['alias']
    if isinstance(v, dict) and 'r' in v:
        return '`%s`' % bt.hexcolor(v)
    if isinstance(v, list):
        return ', '.join(map(str, v)) or '(none)'
    if v is None:
        return '(none)'
    return '`%s`' % (bt.num(v) if isinstance(v, float) else v)


def flat(x, pre=''):
    if isinstance(x, dict):
        out = {}
        for k, v in x.items():
            if k != 'id':
                out.update(flat(v, pre + '.' + k if pre else k))
        return out
    if isinstance(x, list):
        out = {}
        for i, v in enumerate(x):
            out.update(flat(v, '%s[%d]' % (pre, i)))
        return out or {pre: '[]'}
    return {pre: x}


def short(v):
    if isinstance(v, float):
        return bt.num(v)
    return str(v)


def diff(old, new):
    rows, srows = [], []
    ov = {v['id']: (c['name'], v) for c in old['collections'] for v in c['variables']}
    nv = {v['id']: (c['name'], v) for c in new['collections'] for v in c['variables']}
    count = {'added': 0, 'removed': 0, 'renamed': 0, 'changed': 0}
    for i, (c, v) in nv.items():
        if i not in ov:
            count['added'] += 1
            rows.append(('Added', c, v['name'], '—', show(v['value'])))
            continue
        oc, o = ov[i]
        changed = False
        if o['name'] != v['name'] or oc != c:
            count['renamed'] += 1
            rows.append(('Renamed', c, v['name'], '`%s%s`' % ('' if oc == c else oc + ' ', o['name']), '`%s`' % v['name']))
        for f, label in (('value', 'Value'), ('modes', 'Other modes'), ('type', 'Type'), ('scopes', 'Scopes'),
                         ('description', 'Description'), ('codeSyntax', 'Figma code syntax'), ('hidden', 'Hidden')):
            if o.get(f) != v.get(f):
                changed = True
                if f in ('codeSyntax', 'modes'):
                    rows.append((label, c, v['name'], '`%s`' % json.dumps(o.get(f), ensure_ascii=False), '`%s`' % json.dumps(v.get(f), ensure_ascii=False)))
                else:
                    rows.append((label, c, v['name'], show(o.get(f)), show(v.get(f))))
        count['changed'] += changed
    for i, (c, o) in ov.items():
        if i not in nv:
            count['removed'] += 1
            rows.append(('Removed', c, o['name'], show(o['value']), '—'))
    scount = {'added': 0, 'removed': 0, 'renamed': 0, 'changed': 0}
    for kind in ('text', 'effect', 'paint'):
        os_ = {s['id']: s for s in old['styles'][kind]}
        ns = {s['id']: s for s in new['styles'][kind]}
        for i, s in ns.items():
            if i not in os_:
                scount['added'] += 1
                srows.append(('Added', kind, s['name'], ''))
                continue
            o = os_[i]
            if o['name'] != s['name']:
                scount['renamed'] += 1
                srows.append(('Renamed', kind, s['name'], 'was `%s`' % o['name']))
            fo, fn = flat({k: v for k, v in o.items() if k != 'name'}), flat({k: v for k, v in s.items() if k != 'name'})
            d = ['%s: %s → %s' % (k, short(fo.get(k, '—')), short(fn.get(k, '—'))) for k in sorted(set(fo) | set(fn)) if fo.get(k) != fn.get(k)]
            if d:
                scount['changed'] += 1
                srows.append(('Changed', kind, s['name'], '; '.join(d[:6]) + (' …' if len(d) > 6 else '')))
        for i, o in os_.items():
            if i not in ns:
                scount['removed'] += 1
                srows.append(('Removed', kind, o['name'], ''))
    return rows, srows, count, scount


CSS_DEF = re.compile(r'^\s*(--[\w-]+):\s*(.*);', re.M)
CSS_CLS = re.compile(r'^\.([\w-]+) \{(.*)\}', re.M)


def css_items(css):
    d = {n: v for n, v in CSS_DEF.findall(css)}
    d.update({'.' + n: v for n, v in CSS_CLS.findall(css)})
    return d


def cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def entry(version, old, new, rows, srows, count, scount, old_css, new_css, old_info, new_info):
    L = ['## %s' % version['version'], '']
    L.append('%s · exported from Figma by %s (%s) · [%s](%s) · tag `tokens-v%s`' % (
        version['exportedAt'], version.get('exportedBy') or 'unknown', version.get('via') or '?',
        version.get('figmaFile') or 'Figma file', version.get('url') or DEFAULT_URL, version['version']))
    L.append('')
    L.append('**Summary:** ' + summary(count, scount, old_css, new_css))
    L.append('')
    oc, nc = css_items(old_css), css_items(new_css)
    gone = sorted(set(oc) - set(nc))
    renames = {old_info['css_names'][i]: n for i, n in new_info['css_names'].items()
               if i in old_info['css_names'] and old_info['css_names'][i] != n}
    L.append('**Developer impact**')
    L.append('')
    if gone:
        L.append('CSS names removed — update code that uses them:')
        L.append('')
        L.append('| Removed | Use instead |')
        L.append('| --- | --- |')
        for n in gone:
            L.append('| `%s` | %s |' % (n, '`%s`' % renames[n] if n in renames else '—'))
    else:
        L.append('No CSS name was removed or renamed.')
    added = sorted(set(nc) - set(oc))
    revalued = sorted(n for n in set(oc) & set(nc) if oc[n] != nc[n])
    if added:
        L.append('')
        L.append('New CSS names: ' + ', '.join('`%s`' % n for n in added))
    if revalued:
        L.append('')
        L.append('New values for: ' + ', '.join('`%s`' % n for n in revalued))
    if rows:
        L += ['', '**Variables**', '', '| Change | Token | CSS | Before | After |', '| --- | --- | --- | --- | --- |']
        idx = {(c['name'], v['name']): v['id'] for c in new['collections'] for v in c['variables']}
        oidx = {(c['name'], v['name']): v['id'] for c in old['collections'] for v in c['variables']}
        for ch, col, name, before, after in rows:
            vid = idx.get((col, name)) or oidx.get((col, name))
            css = new_info['css_names'].get(vid) or old_info['css_names'].get(vid, '')
            L.append('| %s | %s `%s` | `%s` | %s | %s |' % (ch, col, cell(name), css, cell(before), cell(after)))
    if srows:
        L += ['', '**Styles**', '', '| Change | Style | Detail |', '| --- | --- | --- |']
        for ch, kind, name, detail in srows:
            L.append('| %s | %s `%s` | %s |' % (ch, kind, cell(name), cell(detail)))
    mm = new_info['mismatched']
    if mm != old_info.get('mismatched'):
        L += ['', '<details><summary>Figma code syntax that differs from the naming spec: %d</summary>' % len(mm), '',
              '| Variable | In Figma | Standard (used in CSS) |', '| --- | --- | --- |']
        L += ['| %s `%s` | `%s` | `%s` |' % (c, n, was or '(none)', now) for c, n, was, now in mm]
        L += ['', '</details>']
    return '\n'.join(L) + '\n\n'


def summary(count, scount, old_css=None, new_css=None):
    parts = ['%d %s' % (n, k) for k, n in count.items() if n]
    s = ('variables: ' + ', '.join(parts)) if parts else 'variables unchanged'
    sp = ['%d %s' % (n, k) for k, n in scount.items() if n]
    s += '; styles: ' + (', '.join(sp) if sp else 'unchanged')
    if old_css is not None:
        gone = set(css_items(old_css)) - set(css_items(new_css))
        if gone:
            s += ' — %d CSS name%s removed/renamed' % (len(gone), '' if len(gone) == 1 else 's')
    return s


def next_version(now):
    base = now.strftime('%Y.%m.%d')
    log = open(P['log'], encoding='utf-8').read() if os.path.exists(P['log']) else ''
    taken = set(re.findall(r'^## (\S+)', log, re.M))
    if base not in taken:
        return base
    n = 2
    while '%s.%d' % (base, n) in taken:
        n += 1
    return '%s.%d' % (base, n)


def combine(parts):
    """Join the parts of a paged patch into one."""
    parts = sorted(parts, key=lambda x: x.get('part', 0))
    n = parts[0].get('parts', 1)
    if [x.get('part', 0) for x in parts] != list(range(n)):
        raise SystemExit('Patch incomplete: got parts %s of %d.' % ([x.get('part', 0) for x in parts], n))
    out = {'source': parts[0].get('source', {}), 'digest': parts[0].get('digest'), 'groups': {}}
    for x in parts:
        for k, g in x['groups'].items():
            o = out['groups'].setdefault(k, {'buckets': [], 'items': []})
            o['buckets'] += g['buckets']
            o['items'] += g['items']
    return out


EMPTY = {'schema': 2, 'collections': [], 'styles': {'text': [], 'effect': [], 'paint': []}}


def sync(paths, message_out=None):
    inputs = [json.load(open(p, encoding='utf-8')) for p in paths]
    inp = inputs[0]
    old = rd(P['snap'])
    old_version = rd(P['version'], {})
    if inp.get('unchanged'):
        print('No changes: Figma matches tokens v%s.' % old_version.get('version'))
        return 0
    if 'groups' in inp:
        inp = combine(inputs)
        new = apply_patch(old if old and old.get('schema') == 2 else EMPTY, inp)
    elif 'collections' in inp:
        new = {k: inp[k] for k in ('collections', 'styles')}
    else:
        raise SystemExit('Not a token export: %s' % paths[0])
    new = sort_snapshot({'schema': 2, 'source': inp.get('source', {}), 'collections': new['collections'], 'styles': new['styles']})
    if inp.get('digest') and digest(new) != inp['digest']:
        bad = [k for k in inp['digest'] if digest(new).get(k) != inp['digest'][k]]
        raise SystemExit('Digest mismatch after applying the export (%s). Do a full export instead.' % ', '.join(bad))
    first = not old or old.get('schema') != 2
    if not first and digest(new) == digest(old):
        print('No changes: Figma matches tokens v%s.' % old_version.get('version'))
        return 0

    src = new['source']
    now = datetime.datetime.now(TZ)
    exported = src.get('exportedAt')
    exported = (datetime.datetime.fromisoformat(exported.replace('Z', '+00:00')).astimezone(TZ) if exported else now)
    version = {
        'version': next_version(now),
        'exportedAt': exported.strftime('%Y-%m-%d %H:%M (UTC+8)'),
        'exportedBy': src.get('exportedBy') or ('Claude (Figma MCP)' if src.get('via') == 'mcp' else 'unknown'),
        'via': src.get('via'),
        # use_figma reports the document as "Document"; keep the real file name from earlier versions
        'figmaFile': (src.get('figmaFile') if src.get('figmaFile') not in (None, 'Document') else None)
                     or old_version.get('figmaFile') or 'PeraSure design system',
        'url': ('https://www.figma.com/design/%s' % src['fileKey']) if src.get('fileKey') else (old_version.get('url') or DEFAULT_URL),
        'counts': {c['name']: len(c['variables']) for c in new['collections']},
        'styles': {k: len(v) for k, v in new['styles'].items()},
    }
    version['counts']['styles'] = sum(version['styles'].values())
    files, new_info = outputs(new, version)
    log = open(P['log'], encoding='utf-8').read() if os.path.exists(P['log']) else LOG_HEAD
    if not log.startswith(LOG_HEAD):
        log = LOG_HEAD + log
    if first:
        n = sum(len(c['variables']) for c in new['collections'])
        mm = new_info['mismatched']
        text = ('## %s\n\n%s · exported from Figma by %s (%s) · [%s](%s) · tag `tokens-v%s`\n\n'
                '**Summary:** first versioned export — %d variables (%s), %d text / %d effect / %d paint styles.\n\n'
                % (version['version'], version['exportedAt'], version.get('exportedBy') or 'unknown', version.get('via'),
                   version['figmaFile'], version['url'], version['version'], n,
                   ', '.join('%s %d' % (c['name'], len(c['variables'])) for c in new['collections']),
                   version['styles']['text'], version['styles']['effect'], version['styles']['paint']))
        if mm:
            text += ('<details><summary>Figma code syntax that differs from the naming spec: %d</summary>\n\n'
                     '| Variable | In Figma | Standard (used in CSS) |\n| --- | --- | --- |\n' % len(mm))
            text += ''.join('| %s `%s` | `%s` | `%s` |\n' % (c, nm, was or '(none)', now_) for c, nm, was, now_ in mm)
            text += '\n</details>\n\n'
        line = 'first versioned export, %d variables' % n
        stats = None
    else:
        _, old_info = outputs(old, old_version)
        old_css = open(P['css'], encoding='utf-8').read()
        rows, srows, count, scount = diff(old, new)
        text = entry(version, old, new, rows, srows, count, scount, old_css, files[P['css']], old_info, new_info)
        line = summary(count, scount, old_css, files[P['css']])
        stats = (len(rows), len(srows))
    body = log[len(LOG_HEAD):]
    wr(P['log'], LOG_HEAD + text + body)
    wr(P['snap'], json.dumps(new, ensure_ascii=False, indent=1) + '\n')
    wr(P['version'], json.dumps(version, ensure_ascii=False, indent=1) + '\n')
    for p, t in files.items():
        wr(p, t)
    msg = 'Tokens v%s: %s' % (version['version'], line)
    print(msg)
    if stats:
        print('Changelog: %d variable rows, %d style rows -> tokens/CHANGELOG.md' % stats)
    if new_info['multiMode']:
        print('Note: %s has more than one mode; CSS uses the default mode only.' % ', '.join(new_info['multiMode']))
    print('Tag: tokens-v%s (added by the Tokens workflow on push)' % version['version'])
    if message_out:
        wr(message_out, msg + '\n\nFigma export %s by %s (%s). See tokens/CHANGELOG.md.\n' % (
            version['exportedAt'], version.get('exportedBy') or 'unknown', version.get('via')))
    return 0


def check():
    snap, version = rd(P['snap']), rd(P['version'])
    files, _ = outputs(snap, version)
    stale = [os.path.relpath(p, ROOT) for p, t in files.items()
             if not os.path.exists(p) or open(p, encoding='utf-8').read() != t]
    if stale:
        print('Stale generated files (run python3 tools/build-tokens.py or sync-tokens.py): ' + ', '.join(stale))
        return 1
    print('Tokens v%s: generated files up to date.' % version['version'])
    return 0


def main(argv):
    out = None
    if '--message-out' in argv:
        i = argv.index('--message-out')
        out = argv[i + 1]
        del argv[i:i + 2]
    if argv == ['--digest']:
        print(json.dumps(digest(rd(P['snap'])), separators=(',', ':')))
        return 0
    if argv == ['--check']:
        return check()
    if argv and not any(a.startswith('-') for a in argv):
        return sync(argv, out)
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
