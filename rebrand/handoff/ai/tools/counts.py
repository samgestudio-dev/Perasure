#!/usr/bin/env python3
"""Every count of the package, computed from the data (never typed by hand).

python3 tools/counts.py            print the counts (JSON)
python3 tools/counts.py --write    also rewrite the generated blocks: README.md and 07-motion/README.md between
                                   <!-- counts:begin --> and <!-- counts:end -->, changes-by-file.json meta.counts,
                                   manifest.json "counts" and "files" (sizes)
Python 3.8+, standard library only.
"""
import collections
import glob
import json
import os
import re
import sys

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda *p: os.path.join(PKG, *p)


def load(*p):
    with open(J(*p), encoding='utf-8') as f:
        return json.load(f)


def patch_files(path):
    st = collections.Counter()
    for block in open(path, encoding='utf-8').read().split('diff --git ')[1:]:
        head = block.split('\n@@')[0]
        st['new' if '\nnew file mode' in head else 'deleted' if '\ndeleted file mode' in head else 'modified'] += 1
    return dict(st, total=sum(st.values()))


def compute():
    ch = load('02-changes', 'changes-by-file.json')
    edits = [e for f in ch['files'] for e in f['edits']]
    by_action = collections.Counter(e['action'] for e in edits)
    groups = collections.OrderedDict()
    for f in ch['files']:
        g = groups.setdefault(f['applyGroup'], {'files': 0, 'edits': 0})
        g['files'] += 1
        g['edits'] += len(f['edits'])
    done0 = sum(1 for e in edits if e.get('doneByStep0') or e['action'] == 'token-step')
    skipped = by_action.get('skip', 0) + by_action.get('manual', 0)
    visual = {
        'files': len(ch['files']), 'edits': len(edits),
        'byAction': dict(sorted(by_action.items(), key=lambda kv: -kv[1])),
        'visualEdits': sum(1 for e in edits if e.get('visual')),
        'needsOwner': sum(1 for e in edits if e.get('needsOwner')),
        'doneByStep0': done0,
        'decided20261124': sum(1 for e in edits if str(e.get('decided', '')).startswith('2026-11-24')),
        'structuralOwnerApproved': sum(1 for e in edits if e.get('structural') == 'owner-approved'),
        'byGroup': groups,
        'expectedOnCleanBaseline': {'editsApplied': len(edits) - done0 - skipped, 'editsAlreadyDone': done0,
                                    'editsSkipped': skipped, 'step0Operations': 3},
    }
    assets = load('04-assets', 'assets-to-replace.json')
    rows = [r for k in ('fonts', 'animations', 'logos', 'icons', 'emptyStatesAndIllustrations') for r in assets[k]]
    a = collections.Counter(r.get('applyPy') or 'none' for r in rows)
    visual['assets'] = {'rows': len(rows), 'recolourFiles': a.get('recolour', 0),
                        'removePaths': sum(len(r.get('removePaths', [])) for r in rows if r.get('applyPy') == 'remove'),
                        'codeEditOrKeepOrNeedsDesign': a.get('none', 0)}
    visual['expectedOnCleanBaseline']['assetOperations'] = visual['assets']['recolourFiles'] + visual['assets']['removePaths']
    s8 = load('02-changes', 'step8-tests.json')
    visual['step8TestRewrites'] = len(s8['edits'])
    sp = load('07-motion', 'specs.json')
    st = collections.Counter(m['status'] for m in sp['motions'])
    od = open(J('07-motion', 'OPEN-DECISIONS.md'), encoding='utf-8').read()
    idx = load('07-motion', 'reference', 'index.json')
    motion = {
        'motions': len(sp['motions']), 'done': st.get('done', 0), 'partial': st.get('partial', 0), 'n.a.': st.get('n.a.', 0),
        'rules': len(sp['rules']), 'openDecisions': len(re.findall(r'(?m)^\| \d+ \|', od)),
        'motionPatch': patch_files(J('07-motion', 'motion.patch')),
        'motionOnlyPatch': patch_files(J('07-motion', 'motion-only.patch')),
        'perFilePatches': len([f for f in os.listdir(J('07-motion', 'patches')) if f.endswith('.patch')]),
        'codeFiles': sum(len(fs) for _, _, fs in os.walk(J('07-motion', 'code'))),
        'referenceEntries': len(idx) if isinstance(idx, list) else len(idx.get('motions', idx)),
        'productionTakes': len(glob.glob(J('07-motion', 'verify', 'takes', 'run*', 'curves', '*.json'))),
    }
    return {'visual': visual, 'motion': motion}


def blocks(c):
    v, m = c['visual'], c['motion']
    e = v['expectedOnCleanBaseline']
    ba = ', '.join('%d %s' % (n, k) for k, n in v['byAction'].items())
    main = '\n'.join([
        '| What | Count (generated by `tools/counts.py` from the data) |', '|---|---|',
        '| Edit list `02-changes/changes-by-file.json` | %d files, %d edits: %s |' % (v['files'], v['edits'], ba),
        '| … of which | %d change the look (`visual: true`); %d `needsOwner` (`conflicts.md`); %d carry a 2026-11-24 owner decision, %d of them `structural: "owner-approved"`; %d are done by step 0 |' % (
            v['visualEdits'], v['needsOwner'], v['decided20261124'], v['structuralOwnerApproved'], v['doneByStep0']),
        '| `apply.py --step all` on a clean `0d9bdd4` (expected = proven) | **%d edits applied**, %d already done by step 0, %d skipped, 0 anchor-missing; plus %d step-0 operations, %d asset operations (%d SVG recolours, %d font folders removed) and 1 prettier pass |' % (
            e['editsApplied'], e['editsAlreadyDone'], e['editsSkipped'], e['step0Operations'], e['assetOperations'], v['assets']['recolourFiles'], v['assets']['removePaths']),
        '| Step 8 | every `var(--x, …)` fallback of a token the token file defines, + %d test assertions that pinned a removed fallback (`02-changes/step8-tests.json`) |' % v['step8TestRewrites'],
        '| Motion `07-motion/` | %d motions (%d done, %d partial, %d n.a.), %d rules, %d open decisions; `motion.patch` %d files (%d new, %d modified, %d deleted) = %d per-file patches; `motion-only.patch` %d files |' % (
            m['motions'], m['done'], m['partial'], m['n.a.'], m['rules'], m['openDecisions'], m['motionPatch']['total'], m['motionPatch'].get('new', 0),
            m['motionPatch'].get('modified', 0), m['motionPatch'].get('deleted', 0), m['perFilePatches'], m['motionOnlyPatch']['total']),
    ])
    mot = '\n'.join([
        '| What | Count (generated by `../tools/counts.py`) |', '|---|---|',
        '| Motions in `specs.json` | %d: **%d done, %d partial, %d n.a.**; %d rules |' % (m['motions'], m['done'], m['partial'], m['n.a.'], m['rules']),
        '| `motion.patch` | %d files: %d new, %d modified, %d deleted (no `package.json` / `package-lock.json`: install `motion@14.4.0` with npm first) |' % (
            m['motionPatch']['total'], m['motionPatch'].get('new', 0), m['motionPatch'].get('modified', 0), m['motionPatch'].get('deleted', 0)),
        '| `patches/` | %d per-file patches (`INDEX.txt`), together = `motion.patch` |' % m['perFilePatches'],
        '| `motion-only.patch` | %d files (on the plain `0d9bdd4`) |' % m['motionOnlyPatch']['total'],
        '| `code/` | %d new files in full |' % m['codeFiles'],
        '| `OPEN-DECISIONS.md` | %d questions |' % m['openDecisions'],
        '| `verify/takes/` | %d production curves (3 runs of the kit\'s takes) + `cmp.txt` |' % m['productionTakes'],
    ])
    return main, mot


def put(path, text):
    s = open(path, encoding='utf-8').read()
    new = re.sub(r'<!-- counts:begin -->\n.*?<!-- counts:end -->', lambda mm: '<!-- counts:begin -->\n' + text + '\n<!-- counts:end -->', s, flags=re.S)
    if new == s and '<!-- counts:begin -->' not in s:
        raise SystemExit('no counts block in %s' % path)
    open(path, 'w', encoding='utf-8').write(new)


def main():
    c = compute()
    print(json.dumps(c, indent=1, ensure_ascii=False))
    if '--write' not in sys.argv:
        return
    main_block, mot_block = blocks(c)
    put(J('README.md'), main_block)
    put(J('07-motion', 'README.md'), mot_block)
    ch = load('02-changes', 'changes-by-file.json')
    v = c['visual']
    ch['meta']['counts'] = {k: v[k] for k in ('files', 'edits', 'byAction', 'visualEdits', 'needsOwner', 'doneByStep0', 'decided20261124', 'structuralOwnerApproved', 'byGroup')}
    with open(J('02-changes', 'changes-by-file.json'), 'w', encoding='utf-8') as f:
        json.dump(ch, f, indent=1, ensure_ascii=False)
        f.write('\n')
    man = load('manifest.json')
    man['counts'] = c
    files = []
    for dp, dn, fn in os.walk(PKG):
        dn[:] = sorted(x for x in dn if not x.startswith('.') and x != '__pycache__')
        for f in sorted(fn):
            if f.startswith('.'):
                continue
            rel = os.path.relpath(os.path.join(dp, f), PKG).replace(os.sep, '/')
            if rel.startswith('07-motion/reference/') and rel.count('/') > 2:
                continue  # reference curves / strips / videos: counted, not listed
            files.append({'path': rel, 'bytes': os.path.getsize(os.path.join(dp, f))})
    man['files'] = files
    with open(J('manifest.json'), 'w', encoding='utf-8') as f:
        json.dump(man, f, indent=1, ensure_ascii=False)
        f.write('\n')
    print('written: README.md, 07-motion/README.md, 02-changes/changes-by-file.json meta.counts, manifest.json counts + files')


if __name__ == '__main__':
    main()
